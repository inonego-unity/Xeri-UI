namespace inonego.Xeri.UI
{
    // ============================================================
    /// <summary>
    /// Focus 선택 backend 계약.
    /// </summary>
    // ============================================================
    public interface IFocusDriver
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 현재 선택된 Focus 대상.
        /// </summary>
        // ------------------------------------------------------------
        object Current { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 대상이 현재 선택 가능한지 확인한다.
        /// </summary>
        // ------------------------------------------------------------
        bool IsValid(object target);

        // ------------------------------------------------------------
        /// <summary>
        /// 지정 대상을 현재 Focus로 선택한다.
        /// </summary>
        // ------------------------------------------------------------
        void Select(object target);

        // ------------------------------------------------------------
        /// <summary>
        /// 명시적 대상이 없을 때 사용할 대체 Focus를 찾는다.
        /// </summary>
        // ------------------------------------------------------------
        object FindFallback();
    }
}
