namespace inonego.Xeri.UI
{
    // ============================================================
    /// <summary>
    /// 기본 Focus와 포함 관계를 제공하는 논리적 UI 범위.
    /// </summary>
    // ============================================================
    public interface IFocusScope
    {

    #region 프로퍼티

        // ------------------------------------------------------------
        /// <summary>
        /// 범위가 처음 활성화될 때 사용할 기본 Focus 대상.
        /// </summary>
        // ------------------------------------------------------------
        object DefaultFocus { get; }

    #endregion

    #region 메서드

        // ------------------------------------------------------------
        /// <summary>
        /// 지정 대상이 이 Focus 범위에 속하는지 확인한다.
        /// </summary>
        // ------------------------------------------------------------
        bool ContainsFocus(object target);

    #endregion

    }
}
