using System;

namespace inonego.Xeri.UI
{
    // ============================================================
    /// <summary>
    /// Screen 입력 정책 backend 계약.
    /// </summary>
    // ============================================================
    public interface IScreenInputDriver : IDisposable
    {
        // ------------------------------------------------------------
        /// <summary>
        /// Screen Options에 맞는 입력 정책 Session을 획득한다.
        /// </summary>
        // ------------------------------------------------------------
        ScreenInputSession Acquire(ScreenOptions options);

        // ------------------------------------------------------------
        /// <summary>
        /// 여러 Session 해제 중 중간 상태 적용을 보류한다.
        /// </summary>
        // ------------------------------------------------------------
        void BeginBatch();

        // ------------------------------------------------------------
        /// <summary>
        /// 배치 해제 뒤 계산된 최종 입력 상태를 한 번 적용한다.
        /// </summary>
        // ------------------------------------------------------------
        void EndBatch();

        // ----------------------------------------------------------------------
        /// <summary>
        /// 입력 해제를 기다리는 Session을 포함해 모든 입력 수명을 강제 종결한다.
        /// </summary>
        // ----------------------------------------------------------------------
        void ForceReleaseAll();
    }
}
