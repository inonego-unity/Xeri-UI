namespace inonego.Xeri.UI
{
    // ============================================================
    /// <summary>
    /// Screen 동기 상태 훅 처리 계약.
    /// </summary>
    // ============================================================
    public interface IScreenStateHandler
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 열기 Transition 시작 전에 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        void OnOpening(ScreenStateContext context);

        // ------------------------------------------------------------
        /// <summary>
        /// 열기 Transition 완료 뒤 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        void OnOpened(ScreenStateContext context);

        // ------------------------------------------------------------
        /// <summary>
        /// 닫기 Transition 시작 전에 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        void OnClosing(ScreenStateContext context);

        // ------------------------------------------------------------
        /// <summary>
        /// 닫기 Transition과 하위 표시 정리 뒤 호출된다.
        /// </summary>
        // ------------------------------------------------------------
        void OnClosed(ScreenStateContext context);
    }
}
