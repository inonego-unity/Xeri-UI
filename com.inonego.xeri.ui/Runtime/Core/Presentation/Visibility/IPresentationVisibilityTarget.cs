# 설명
PresentationVisibility가 최종 표시 상태를 읽고 적용할 backend Target 계약을 정의한다.
Target은 UI 종류나 소유권을 나타내지 않고 Visibility 적용 경계만 제공한다.
========================================================================= BLOCK_HEADER_END */

namespace inonego.Xeri.UI
{
    // ============================================================
    /// <summary>
    /// Presentation Visibility의 최종 backend 적용 계약.
    /// </summary>
    // ============================================================
    public interface IPresentationVisibilityTarget
    {
        // ------------------------------------------------------------
        /// <summary>
        /// Target이 현재 Visibility 상태를 적용할 수 있는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        bool IsValid { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 backend 표시 상태.
        /// </summary>
        // ------------------------------------------------------------
        bool IsVisible { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 최종 표시 상태를 backend에 적용한다.
        /// </summary>
        // ------------------------------------------------------------
        void SetVisible(bool visible);
    }

}
