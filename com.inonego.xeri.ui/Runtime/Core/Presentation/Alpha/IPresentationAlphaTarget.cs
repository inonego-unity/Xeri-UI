namespace inonego.Xeri.UI
{
    // ============================================================
    /// <summary>
    /// Presentation Alpha의 최종값을 적용하는 backend Target 계약.
    /// </summary>
    // ============================================================
    public interface IPresentationAlphaTarget
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 현재 Target이 Alpha를 읽고 적용할 수 있는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        bool IsValid { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 backend Alpha.
        /// </summary>
        // ------------------------------------------------------------
        float Alpha { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 합성된 최종 Alpha를 backend에 적용한다.
        /// </summary>
        // ------------------------------------------------------------
        void SetAlpha(float alpha);
    }
}
