namespace inonego.Xeri.UI
{
    // ============================================================
    /// <summary>
    /// backend별 Spotlight 표시 계약.
    /// </summary>
    // ============================================================
    public interface ISpotlightDriver<in TParams>
    where TParams : class
    {
        // ------------------------------------------------------------
        /// <summary>
        /// backend가 현재 표시 요청을 받을 수 있는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        bool IsValid { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 Spotlight 표시 인자를 적용한다.
        /// </summary>
        // ------------------------------------------------------------
        void Show(TParams parameters);

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 Spotlight 표시를 숨긴다.
        /// </summary>
        // ------------------------------------------------------------
        void Hide();
    }
}
