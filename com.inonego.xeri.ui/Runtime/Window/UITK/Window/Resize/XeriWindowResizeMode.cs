namespace inonego.Xeri.UI.Window
{
    // ============================================================
    /// <summary>
    /// Window resize 입력 방향.
    /// </summary>
    // ============================================================
    public enum XeriWindowResizeMode
    {
        // ------------------------------------------------------------
        /// <summary>
        /// Resize 방향이 지정되지 않은 상태.
        /// </summary>
        // ------------------------------------------------------------
        None = 0,

        // ------------------------------------------------------------
        /// <summary>
        /// Window 왼쪽 경계 리사이즈.
        /// </summary>
        // ------------------------------------------------------------
        Left = 1,

        // ------------------------------------------------------------
        /// <summary>
        /// Window 위쪽 경계 리사이즈.
        /// </summary>
        // ------------------------------------------------------------
        Top = 2,

        // ------------------------------------------------------------
        /// <summary>
        /// Window 오른쪽 경계 리사이즈.
        /// </summary>
        // ------------------------------------------------------------
        Right = 3,

        // ------------------------------------------------------------
        /// <summary>
        /// Window 아래쪽 경계 리사이즈.
        /// </summary>
        // ------------------------------------------------------------
        Bottom = 4,

        // ------------------------------------------------------------
        /// <summary>
        /// Window 왼쪽 위 모서리 리사이즈.
        /// </summary>
        // ------------------------------------------------------------
        TopLeft = 5,

        // ------------------------------------------------------------
        /// <summary>
        /// Window 오른쪽 위 모서리 리사이즈.
        /// </summary>
        // ------------------------------------------------------------
        TopRight = 6,

        // ------------------------------------------------------------
        /// <summary>
        /// Window 왼쪽 아래 모서리 리사이즈.
        /// </summary>
        // ------------------------------------------------------------
        BottomLeft = 7,

        // ------------------------------------------------------------
        /// <summary>
        /// Window 오른쪽 아래 모서리 리사이즈.
        /// </summary>
        // ------------------------------------------------------------
        BottomRight = 8,
    }
}
