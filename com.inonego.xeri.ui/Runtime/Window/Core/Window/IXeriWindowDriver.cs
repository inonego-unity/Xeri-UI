using UnityEngine;

namespace inonego.Xeri.UI.Window
{
    // ============================================================
    /// <summary>
    /// Xeri 커스텀 윈도우 표시 driver 계약.
    /// </summary>
    // ============================================================
    public interface IXeriWindowDriver : IPresentation
    {

    #region 프로퍼티

        // ------------------------------------------------------------
        /// <summary>
        /// 윈도우 위치.
        /// </summary>
        // ------------------------------------------------------------
        Vector2 Pos { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// 윈도우 크기.
        /// </summary>
        // ------------------------------------------------------------
        Vector2 Size { get; set; }

        // ------------------------------------------------------------
        /// <summary>
        /// 윈도우 표시 상태.
        /// </summary>
        // ------------------------------------------------------------
        XeriWindowState State { get; }

        // ------------------------------------------------------------
        /// <summary>
        /// 현재 위치와 크기를 하나의 bounds로 반환하거나 반영한다.
        /// </summary>
        // ------------------------------------------------------------
        Rect Bounds { get; set; }

    #endregion

    #region 메서드

        // ------------------------------------------------------------
        /// <summary>
        /// 상태 class와 상태 값만 즉시 반영한다.
        /// </summary>
        // ------------------------------------------------------------
        void CommitState(XeriWindowState state);

        // ------------------------------------------------------------
        /// <summary>
        /// 완료 상태 값은 유지하고 전환 중 시각 상태만 즉시 반영한다.
        /// </summary>
        // ------------------------------------------------------------
        void ApplyVisualState(XeriWindowState state);

        // ------------------------------------------------------------
        /// <summary>
        /// Normal bounds를 즉시 반영한다.
        /// </summary>
        // ------------------------------------------------------------
        void ApplyBounds(Rect bounds);

        // ------------------------------------------------------------
        /// <summary>
        /// 부모 영역을 채우는 maximized bounds를 즉시 반영한다.
        /// </summary>
        // ------------------------------------------------------------
        void ApplyMaximizedBounds();

    #endregion

    }
}
