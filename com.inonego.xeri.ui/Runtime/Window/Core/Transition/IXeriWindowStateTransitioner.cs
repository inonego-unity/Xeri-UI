namespace inonego.Xeri.UI.Window
{
   // ============================================================
   /// <summary>
   /// Xeri window 상태 전환 조율 계약.
   /// </summary>
   // ============================================================
   public interface IXeriWindowStateTransitioner
   {

   #region 프로퍼티

      // ------------------------------------------------------------
      /// <summary>
      /// 현재 전환 실행 상태.
      /// </summary>
      // ------------------------------------------------------------
      XeriWindowTransitionStatus Status { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 전환 실행 중 여부.
      /// </summary>
      // ------------------------------------------------------------
      bool IsRunning { get; }

      // ------------------------------------------------------------
      /// <summary>
      /// 진행 중 전환 목표 상태.
      /// </summary>
      // ------------------------------------------------------------
      XeriWindowState? PendingState { get; }

   #endregion

   #region 메서드

      // ------------------------------------------------------------
      /// <summary>
      /// 상태 전환을 시작한다.
      /// </summary>
      // ------------------------------------------------------------
      bool Transition(XeriWindowStateTransitionRequest request);

      // ------------------------------------------------------------
      /// <summary>
      /// 진행 중 상태 전환을 취소한다.
      /// </summary>
      // ------------------------------------------------------------
      void Cancel(bool restoreVisual);

   #endregion

   }
}
